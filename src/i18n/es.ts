/** ["correo", "teléfono", "ubicación"] -> "correo, teléfono ni ubicación". */
function listEs(items: string[]): string {
  return items.length <= 1 ? items.join("") : `${items.slice(0, -1).join(", ")} ni ${items[items.length - 1]}`;
}

